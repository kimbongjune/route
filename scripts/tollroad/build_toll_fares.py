def add(road, start, end, kind, fare, time="", note=""):
    ROWS.append({"도로": road, "출발": start, "도착": end, "차종": kind, "요금": fare, "시간대": time, "비고": note})


def by_gate(road, kinds, gates, table, note=""):
    """table[i][j] = kinds[i] 차종의 gates[j] 영업소 요금."""
    for kind, vals in zip(kinds, table):
        for gate, v in zip(gates, vals):
            add(road, gate, "", kind, v, note=note)


def od(road, kind, nodes, matrix, cols=None, note=""):
    """matrix[i][j] = nodes[i] -> cols[j] 요금. None 은 원문 '-'(요금 없음/진출 불가)."""
    cols = cols or nodes
    for a, vals in zip(nodes, matrix):
        for b, v in zip(cols, vals):
            if v is not None and a != b:
                add(road, a, b, kind, v, note=note)


def flat(road, pairs, gate="", note="", time=""):
    for kind, v in pairs:
        add(road, gate, "", kind, v, time=time, note=note)


