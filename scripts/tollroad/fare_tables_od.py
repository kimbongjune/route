# 단거리 연계구간 통행료(이 세 구간은 위 표 대신 이 요금 적용, 차종 구분 없음)
SEOBU_NAERYUK_SHORT = [("포승JCT", "포승IC", 100), ("예산JCT", "예산예당호IC", 300), ("부여JCT", "부여구룡IC", 200)]


def parse(nodes, text):
    """표 텍스트를 (출발, 도착, 요금, 괄호 요금 또는 None) 목록으로 바꾼다."""
    cols = nodes.split()
    out = []
    for line in text.strip().splitlines():
        parts = line.split()
        src, vals = parts[0], parts[1:]
        assert len(vals) == len(cols), (src, len(vals), len(cols))
        for dst, v in zip(cols, vals):
            if v == "-" or src == dst:
                continue
            alt = None
            if "(" in v:
                v, alt = v.rstrip(")").split("(")
                alt = int(alt.replace(",", ""))
            out.append((src, dst, int(v.replace(",", "")), alt))
    return out
